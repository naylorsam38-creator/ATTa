"""Configuration resolution (Stage 01B §7). Precedence, highest first:
  1 trusted operator overrides (configuration/operator.yaml)   2 local environment configuration (local.yaml,
  local.env, ATTA__ variables)   3 deployment profile (configuration/profiles/<p>.yaml)   4 discovered values
  (runtime/deployment/discovered.yaml)   5 application defaults (base.yaml + environments/<env>.yaml).
The effective configuration is generated separately from the immutable templates, validated before any service is
activated, and reported with per-value provenance and every secret redacted."""
from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from backend.settings import ConfigurationError, Settings, load_settings
from backend.settings.loader import ENV_PREFIX, REPO_ROOT, SECRET_FIELDS, _read_yaml, parse_env_file

from .manifest import redact

ENV_NAME = re.compile(r"^[A-Z_][A-Z0-9_]{0,99}$")


@dataclass
class Resolution:
    settings: Settings | None
    effective: dict
    provenance: dict[str, str]
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def valid(self) -> bool:
        return self.settings is not None and not self.errors


def _leaves(d: dict, prefix: str = "") -> dict[str, object]:
    out = {}
    for k, v in d.items():
        key = f"{prefix}.{k}" if prefix else str(k)
        if isinstance(v, dict) and v:
            out.update(_leaves(v, key))
        else:
            out[key] = v
    return out


def write_discovered(directory: Path, decision, env: dict) -> Path:
    """Layer 4: values derived from discovery (non-secret). Written only by the installer/run path."""
    r = decision.resources or {}
    layer = {"deployment": {"profile": decision.selected, "model_context_tokens": r.get("model_context_tokens", 4096),
                            "controller_caps": r.get("controller_caps", {})},
             "workers": {"max_concurrency": r.get("worker_count", 2), "memory_limit_mb": r.get("worker_memory_mb", 1024)}}
    directory.mkdir(parents=True, exist_ok=True)
    p = directory / "discovered.yaml"
    p.write_text("# GENERATED by backend.deployment from machine discovery — do not edit (layer 4 of 5)\n" +
                 yaml.safe_dump(layer, sort_keys=True))
    return p


def resolve(environment: str | None = None, *, root: Path = REPO_ROOT, env: dict | None = None,
            profile: str | None = None, discovered_dir: Path | None = None) -> Resolution:
    environ = dict(os.environ if env is None else env)
    if profile:
        environ["ATTA_PROFILE"] = profile
    if discovered_dir is not None:
        environ["ATTA_DEPLOYMENT_DIR"] = str(discovered_dir.relative_to(root)) if root in discovered_dir.parents \
            else str(discovered_dir)
    errors, warnings = [], []
    try:
        settings = load_settings(environment, root=root, env=environ)
    except ConfigurationError as exc:
        return Resolution(None, {}, {}, exc.problems)
    # provenance: recompute which layer last set each leaf
    cfg = root / "configuration"
    envname = settings.environment.value
    layers = [("default", _read_yaml(cfg / "base.yaml")), ("default", _read_yaml(cfg / "environments" / f"{envname}.yaml"))]
    ddir = Path(environ.get("ATTA_DEPLOYMENT_DIR") or "runtime/deployment")
    ddir = ddir if ddir.is_absolute() else root / ddir
    layers.append(("discovered", _read_yaml(ddir / "discovered.yaml")))
    prof = settings.deployment.profile.lower()
    if prof != "auto":
        layers.append(("profile:" + settings.deployment.profile, _read_yaml(cfg / "profiles" / f"{prof}.yaml")))
    layers.append(("local", _read_yaml(cfg / "local.yaml")))
    envlayer: dict = {}
    for k, v in {**parse_env_file(cfg / "local.env"), **environ}.items():
        if k.startswith(ENV_PREFIX):
            cur = envlayer
            parts = [p.lower() for p in k[len(ENV_PREFIX):].split("__") if p]
            for p in parts[:-1]:
                cur = cur.setdefault(p, {})
            if parts:
                cur[parts[-1]] = v
    layers.append(("local-environment", envlayer))
    layers.append(("operator", _read_yaml(cfg / "operator.yaml")))
    provenance: dict[str, str] = {}
    for name, layer in layers:
        for k in _leaves(layer or {}):
            provenance[k] = name
    for (section, key), var in SECRET_FIELDS.items():
        if getattr(getattr(settings, section), key, None) is not None:
            provenance[f"{section}.{key}"] = f"secret:{var}"
    effective = redact(json.loads(settings.model_dump_json()))
    # ---------------------------------------------------------------- validation
    if settings.database.password is None:
        errors.append("database.password missing: set ATTA_DATABASE_PASSWORD (local.env or environment)")
    used: dict[int, str] = {}
    for name, port in (("api", settings.api.port), ("redis", settings.redis.port), ("postgres", settings.database.port)):
        if port in used and not (name == "postgres" and settings.services.get("postgres", None) and
                                 settings.services["postgres"].mode == "external"):
            errors.append(f"port conflict: {name} and {used[port]} both use {port}")
        used.setdefault(port, name)
    for p in settings.models.storage_paths:
        pp = Path(p)
        if pp.exists() and not pp.is_dir():
            errors.append(f"model path {p} exists but is not a directory")
        elif not pp.exists():
            warnings.append(f"model path {p} not present now (removable drive not attached?)")
    known_rt = {"llamacpp", "ollama", "vllm"}
    bad_rt = [r for r in settings.deployment.runtime_preference if r not in known_rt]
    if bad_rt:
        errors.append(f"unsupported runtimes in runtime_preference: {bad_rt}")
    for e in settings.models.endpoints:
        if e.api_key_env and not ENV_NAME.match(e.api_key_env):
            errors.append(f"model endpoint {e.name}: invalid secret reference {e.api_key_env!r}")
        if e.enabled and e.kind not in ("ollama", "llamacpp", "vllm", "openai_compatible", "litellm") and \
                not settings.security.allow_paid_infrastructure:
            warnings.append(f"model endpoint {e.name} is a remote provider and stays unused (no external fallback)")
    return Resolution(settings, effective, provenance, errors, warnings)


def validate_against_environment(res: Resolution, env: dict, decision) -> None:
    """Checks needing discovery results: GPU/runtime combinations, mandatory services, live port conflicts."""
    s = res.settings
    gpu = bool(env.get("gpu", {}).get("present"))
    if s.deployment.gpu_visible_to_workers and not gpu:
        res.errors.append("gpu_visible_to_workers is set but no NVIDIA GPU is present")
    for e in s.models.endpoints:
        if e.enabled and e.kind == "vllm" and not gpu:
            res.errors.append(f"model endpoint {e.name}: vLLM enabled without an NVIDIA GPU")
    if not decision.compatible:
        res.errors += [f"profile {decision.requested}: {r}" for r in decision.reasons]
    for name, spec in s.services.items():
        if spec.essential and spec.mode == "external" and name not in ("controller",):
            st = env.get("services", {}).get(name)
            if st is not None and not st.get("healthy"):
                res.errors.append(f"mandatory external service '{name}' unavailable: {st.get('detail')}")
    for name, p in env.get("ports", {}).items():
        svc = s.services.get(name)
        if p.get("in_use") and svc is not None and svc.mode == "managed":
            res.warnings.append(f"port {p['port']} for managed service '{name}' is in use now (conflict unless it is "
                                "this installation's own running service)")


def report(res: Resolution, decision=None) -> str:
    lines = ["ATTa effective configuration report", "=" * 36]
    if decision is not None:
        lines += [f"profile requested: {decision.requested}  selected: {decision.selected}  "
                  f"compatible: {decision.compatible}"] + [f"  ! {r}" for r in decision.reasons]
    lines += [f"valid: {res.valid}"] + [f"  ERROR: {e}" for e in res.errors] + [f"  warning: {w}" for w in res.warnings]
    lines.append("")
    flat = _leaves(res.effective)
    for k in sorted(flat):
        lines.append(f"{k} = {json.dumps(flat[k], default=str)}    [{res.provenance.get(k, 'default')}]")
    return "\n".join(lines) + "\n"
