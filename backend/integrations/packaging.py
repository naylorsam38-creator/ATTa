"""Generate the Stage 01A capability package for an APPROVED integration version (Stage 12 §23).

Integrations do not get a second registry: an approved integration becomes an ordinary capability package
(`capability.yaml` + the integration's own files + ATTa-supplied bridge/verify/health modules) in the managed
install root, discovered by the ONE CapabilityRegistry and numbered in the ONE tool catalogue. Generated modules
contain only validated identifiers and JSON literals; the approved configuration is embedded in code so it is
covered by the package digest that the runtime re-verifies before every execution."""
from __future__ import annotations

import json
import shutil
from dataclasses import dataclass
from pathlib import Path

import yaml

from backend.capability_registry.package import package_digest

from .manifest import MANIFEST_FILENAME, IntegrationManifest
from .types import CAPABILITY_ID_PREFIX, RISK_ORDER, IntegrationType

# Bridge files are TEMPLATES (*.py.tmpl): they import modules that exist only inside a generated package
# (_atta_schemas, _atta_mcp_tools, _atta_mcp_wire), so they are not backend modules and are not scanned as such.
BRIDGES = Path(__file__).with_name("bridges")
MCP_ENVELOPE = {"type": "object", "additionalProperties": False, "required": ["content", "is_error"],
                "properties": {"content": {"type": "array", "maxItems": 500, "items": {"type": "object"}},
                               "structured_content": {}, "is_error": {"type": "boolean"}}}


def capability_id_for(integration_id: str) -> str:
    return CAPABILITY_ID_PREFIX + integration_id


def tool_output_schema(m: IntegrationManifest, t: dict) -> dict:
    if m.type is IntegrationType.MCP_SERVER:
        env = json.loads(json.dumps(MCP_ENVELOPE))
        env["properties"]["structured_content"] = {"anyOf": [{"type": "null"}, t["output_schema"]]}
        return env
    return t["output_schema"]


def has_executable_tools(m: IntegrationManifest) -> bool:
    return bool(m.tools)


@dataclass(frozen=True)
class GeneratedPackage:
    directory: Path
    capability_id: str
    source_digest: str        # digest of the copied integration files (must equal the approved package digest)
    package_digest: str       # digest of the complete generated capability package (what the registry verifies)


def _module_literal(name: str, value) -> str:
    return f"{name} = json.loads({json.dumps(json.dumps(value, sort_keys=True))})\n"


def build_package(m: IntegrationManifest, staging: Path, *, request_timeout_s: float, startup_timeout_s: float,
                  dependency_capabilities: list[str] | None = None) -> GeneratedPackage:
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    # 1. copy exactly the validated files (no symlinks; validation already refused them)
    for rel in m.files:
        src = m.directory / rel
        if src.is_symlink():
            raise ValueError(f"symlink appeared in package after validation: {rel}")
        dst = staging / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
    source_digest = package_digest(staging) if m.files else ""
    if m.package_digest and source_digest != m.package_digest:
        raise ValueError("copied package bytes differ from the approved package digest")
    cap_id = capability_id_for(m.integration_id)
    tools = m.tools
    is_mcp = m.type is IntegrationType.MCP_SERVER
    # 2. ATTa-supplied modules
    schemas = {t["name"]: tool_output_schema(m, t) for t in tools}
    (staging / "_atta_schemas.py").write_text('"""GENERATED by ATTa Stage 12 — approved output schemas."""\nimport json\n'
                                              + _module_literal("OUTPUT_SCHEMAS", schemas))
    shutil.copyfile(BRIDGES / "verify.py.tmpl", staging / "_atta_verify.py")
    vlines = ['"""GENERATED by ATTa Stage 12 — per-tool independent verifiers."""',
              "from _atta_verify import verify_with", ""]
    for t in tools:
        vlines.append(f"def v_{t['name']}(payload, output):\n    return verify_with({t['name']!r}, output)\n")
    (staging / "_atta_tools_verify.py").write_text("\n".join(vlines))
    health_ref = "_atta_health:healthcheck"
    if is_mcp:
        shutil.copyfile(Path(__file__).with_name("mcp") / "wire.py", staging / "_atta_mcp_wire.py")
        shutil.copyfile(BRIDGES / "mcp_bridge.py.tmpl", staging / "_atta_mcp_bridge.py")
        cfg = {"mcp": m.raw["mcp"], "request_timeout_s": request_timeout_s, "startup_timeout_s": startup_timeout_s,
               "tools": {t["name"]: {"mcp_name": t.get("mcp_name", t["name"])} for t in tools}}
        lines = ['"""GENERATED by ATTa Stage 12 — approved MCP configuration and tool entry points."""', "import json",
                 _module_literal("CONFIG", cfg), ""]
        for t in tools:
            lines.append(f"def t_{t['name']}(payload, ctx):\n    import _atta_mcp_bridge\n"
                         f"    return _atta_mcp_bridge.call({t['name']!r}, payload, ctx)\n")
        lines.append("def healthcheck():\n    import _atta_mcp_bridge\n    return _atta_mcp_bridge.healthcheck()\n")
        (staging / "_atta_mcp_tools.py").write_text("\n".join(lines))
        health_ref = "_atta_mcp_tools:healthcheck"
    else:
        h = (m.raw.get("health") or {}).get("handler")
        if h:
            mod, fn = h.split(":")
            (staging / "_atta_health.py").write_text(
                '"""GENERATED by ATTa Stage 12 — delegates to the declared health handler."""\n'
                f"def healthcheck():\n    from {mod} import {fn} as _h\n    return _h()\n")
        else:
            shutil.copyfile(BRIDGES / "health.py.tmpl", staging / "_atta_health.py")
    # 3. capability.yaml for the existing registry
    ctools = []
    for t in tools:
        rs = t.get("resource_scope") or {}
        ctools.append({
            "name": t["name"], "description": t["description"], "task_types": t["task_types"],
            "operations": t["operations"],
            "handler": f"_atta_mcp_tools:t_{t['name']}" if is_mcp else t["handler"],
            "verify": f"_atta_tools_verify:v_{t['name']}",
            "input_schema": t["input_schema"], "output_schema": tool_output_schema(m, t),
            "permissions": sorted(t["permissions"]), "risk": t["risk"],
            "resource_types": rs.get("resource_types") or [], "path_arguments": rs.get("path_arguments") or [],
            "url_arguments": rs.get("url_arguments") or [], "timeout_s": t["timeout_s"],
            "cancellable": t["cancellable"], "idempotency": t["idempotency"]})
    first = ctools[0]["handler"]
    cap = {"manifest_version": 1, "id": cap_id, "version": m.version,
           "description": f"{m.type.value} integration '{m.raw['name']}' (Stage 12 generated package): "
                          f"{m.raw['description']}"[:2000],
           "requirement": m.requirement,
           "handlers": {"execute": first, "healthcheck": health_ref, "verify": f"_atta_tools_verify:v_{tools[0]['name']}"},
           "input_schema": {"type": "object"}, "output_schema": {"type": "object"},
           "permissions": sorted(m.permissions), "risk": max((t["risk"] for t in tools), key=lambda r: RISK_ORDER[r]),
           "dependencies": {"capabilities": sorted(dependency_capabilities or []), "services": [],
                            "python": list((m.raw.get("dependencies") or {}).get("python") or [])},
           "timeout_s": max(t["timeout_s"] for t in tools), "enabled": True, "tools": ctools}
    (staging / "capability.yaml").write_text("# GENERATED by ATTa Stage 12 from the approved integration manifest. "
                                             "Do not edit.\n" + yaml.safe_dump(cap, sort_keys=False))
    (staging / "_atta_integration.json").write_text(json.dumps(
        {"integration_id": m.integration_id, "version": m.version, "manifest_digest": m.manifest_digest,
         "source_package_digest": m.package_digest, "integration_type": m.type.value}, indent=2, sort_keys=True))
    if (staging / MANIFEST_FILENAME).exists() is False and m.files:
        raise ValueError("integration manifest missing from the generated package")
    return GeneratedPackage(staging, cap_id, source_digest, package_digest(staging))
