#!/usr/bin/env python3
"""Write CHANGE_MANIFEST.md: every file added/modified/deleted since a base commit, grouped by area, with SHA-256.
  python scripts/generate_change_manifest.py [--base <commit>] [--stage S01]"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def git(*a: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True, text=True, check=True).stdout


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--range", action="append", default=None,
                    help="STAGE:BASE[:END] (END omitted = working tree); repeatable, newest last")
    a = ap.parse_args()
    ranges = a.range or ["S01:cef732913714fdcc5e58ae35ce4c484032289ec0:fa406b322c7aff77eac4d8bcc88f790732004649",
                         "S01A:b4f5c25"]
    doc = ["# CHANGE MANIFEST", "",
           "Generated by `python scripts/generate_change_manifest.py`. One section per stage, newest first. "
           "Build-controller run evidence (`evidence/build_controller/`) is excluded; it is listed in the stage "
           "verification reports.", ""]
    for spec in reversed(ranges):
        stage, base, *end = spec.split(":")
        doc += section(stage, base, end[0] if end else None)
    (ROOT / "CHANGE_MANIFEST.md").write_text("\n".join(doc))
    print("CHANGE_MANIFEST.md written for " + ", ".join(r.split(":")[0] for r in ranges))
    return 0


def section(stage: str, base: str, end: str | None) -> list[str]:
    class A:
        pass
    a = A()
    a.base, a.stage = base, stage
    rows = []
    diff_args = ["diff", "--name-status", "--no-renames", a.base] + ([end] if end else [])
    for line in git(*diff_args).splitlines():
        st, path = line.split("\t", 1)
        rows.append((st, path))
    if not end:
        rows += [("A", p) for p in git("ls-files", "--others", "--exclude-standard").splitlines()]
    rows = sorted(set(r for r in rows if not r[1].startswith("evidence/build_controller/")), key=lambda r: r[1])
    groups: dict[str, list] = defaultdict(list)
    for st, path in rows:
        top = path.split("/")[0] if "/" in path else "(root)"
        if top in ("backend", "apps", "packages", "tests", "infrastructure", "configuration", "database"):
            top = "/".join(path.split("/")[:2]) if path.count("/") >= 2 else top
        p = ROOT / path
        digest = hashlib.sha256(p.read_bytes()).hexdigest()[:16] if p.is_file() else "—"
        groups[top].append((st, path, digest))
    names = {"A": "added", "M": "modified", "D": "deleted"}
    out = [f"## Stage {a.stage[1:]} — {a.base[:12]}..{(end or 'working tree')[:12]}", "",
           f"Totals: {sum(1 for r in rows if r[0] == 'A')} added, {sum(1 for r in rows if r[0] == 'M')} modified, "
           f"{sum(1 for r in rows if r[0] == 'D')} deleted.", "",
           "Pre-existing ATTa v121.5 files: unchanged except additive `README.md`/`.gitignore` edits (S01-T16)." if
           a.stage == "S01" else "Stage 01 acceptance tests and helpers are unchanged (protected by the S01A stage).",
           ""]
    for g in sorted(groups):
        out += [f"### {g}", "", "| Change | Path | SHA-256 (16) |", "|---|---|---|"]
        out += [f"| {names.get(st, st)} | `{p}` | `{d}` |" for st, p, d in groups[g]]
        out.append("")
    return out


if __name__ == "__main__":
    raise SystemExit(main())
