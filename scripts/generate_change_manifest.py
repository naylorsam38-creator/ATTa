#!/usr/bin/env python3
"""Write CHANGE_MANIFEST.md: every file added/modified/deleted since a base commit, grouped by area, with SHA-256.
  python scripts/generate_change_manifest.py [--base <commit>] [--stage S01]"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def git(*a: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True, text=True, check=True).stdout


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="cef732913714fdcc5e58ae35ce4c484032289ec0")
    ap.add_argument("--stage", default="S01")
    a = ap.parse_args()
    rows = []
    for line in git("diff", "--name-status", "--no-renames", a.base).splitlines():
        st, path = line.split("\t", 1)
        rows.append((st, path))
    rows += [("A", p) for p in git("ls-files", "--others", "--exclude-standard").splitlines()]
    rows = sorted(set(r for r in rows if not r[1].startswith("evidence/build_controller/")), key=lambda r: r[1])
    groups: dict[str, list] = defaultdict(list)
    for st, path in rows:
        top = path.split("/")[0] if "/" in path else "(root)"
        if top in ("backend", "apps", "packages", "tests", "infrastructure", "configuration", "database"):
            top = "/".join(path.split("/")[:2]) if path.count("/") >= 2 else top
        p = ROOT / path
        digest = hashlib.sha256(p.read_bytes()).hexdigest()[:16] if p.is_file() else "—"
        groups[top].append((st, path, digest))
    names = {"A": "added", "M": "modified", "D": "deleted"}
    out = [f"# CHANGE MANIFEST — Stage {a.stage[1:]}", "",
           f"Generated by `python scripts/generate_change_manifest.py` against base commit `{a.base}` "
           "(ATTa v121.5). Build-controller run evidence (`evidence/build_controller/`) is excluded; it is listed "
           "in STAGE_01_VERIFICATION.md.", "",
           f"Totals: {sum(1 for r in rows if r[0] == 'A')} added, {sum(1 for r in rows if r[0] == 'M')} modified, "
           f"{sum(1 for r in rows if r[0] == 'D')} deleted.", "",
           "Modified pre-existing files are additive only (verified by S01-T16): `README.md` (new top section), "
           "`.gitignore` (new entries). No pre-existing file was deleted.", ""]
    for g in sorted(groups):
        out += [f"## {g}", "", "| Change | Path | SHA-256 (16) |", "|---|---|---|"]
        out += [f"| {names.get(st, st)} | `{p}` | `{d}` |" for st, p, d in groups[g]]
        out.append("")
    (ROOT / "CHANGE_MANIFEST.md").write_text("\n".join(out))
    print(f"CHANGE_MANIFEST.md: {len(rows)} entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
