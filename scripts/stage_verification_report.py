#!/usr/bin/env python3
"""Render STAGE_01_VERIFICATION.md from the build-controller ledger and evidence files (never from memory).
  python scripts/stage_verification_report.py [--stage S01] [--run <run-id>]   (default: latest gate run)"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.verification.build_controller import BuildController  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="S01")
    ap.add_argument("--run")
    a = ap.parse_args()
    bc = BuildController(ROOT)
    ledger = bc.ledger()
    gates = [r for r in ledger if r["type"] == "stage_gate" and r["stage"] == a.stage]
    gate = next((g for g in reversed(gates) if not a.run or g["run"] == a.run), None)
    out = [f"# STAGE {a.stage[1:]} VERIFICATION", "",
           "Generated by `python scripts/stage_verification_report.py` from `evidence/build_controller/ledger.jsonl`"
           " and the per-test evidence files it references. Every result below is an executed command.", ""]
    if gate is None:
        out += ["**No stage gate has been recorded yet.** Run `python -m backend.verification verify-stage "
                f"{a.stage}`.", ""]
        (ROOT / "STAGE_01_VERIFICATION.md").write_text("\n".join(out))
        return 0
    run = gate["run"]
    integrity = bc.check_integrity() + bc.verify_ledger()
    cps = [c for c in bc.checkpoints() if c.get("run") == run]
    out += [f"## Gate result: **{gate['status']}**", "",
            f"* Run: `{run}` — recorded {gate['recorded_at']}",
            f"* Code under test (HEAD): `{gate['head']}` — stage base: `{gate['base']}`",
            f"* Ledger record hash: `{gate['hash']}`",
            f"* Protected criteria + ledger integrity now: {'INTACT' if not integrity else '; '.join(integrity)}",
            f"* File-authorisation problems: {len(gate['file_problems'])}"
            + "".join(f"\n  * {p}" for p in gate["file_problems"]),
            f"* Recovery checkpoint: {json.dumps(cps[-1]) if cps else 'none recorded for this run'}", "",
            "## Tasks", "", "| Task | Status |", "|---|---|"]
    out += [f"| {t} | **{s}** |" for t, s in gate["tasks"].items()]
    out += ["", "## Acceptance tests (command, exit code, timestamps, output)", ""]
    tests = [r for r in ledger if r["type"] == "test_result" and r["run"] == run]
    out += ["| Test | Task | Result | Exit | Expected | Started (UTC) | Finished (UTC) | Evidence |",
            "|---|---|---|---|---|---|---|---|"]
    for r in tests:
        out.append(f"| {r['test']} | {r['task']} | {'PASS' if r['passed'] else 'FAIL'} | {r['exit_code']} | "
                   f"{r['expected_exit_code']} | {r['started_at']} | {r['finished_at']} | `{r['evidence_file']}` |")
    out.append("")
    for r in tests:
        ev = json.loads((ROOT / r["evidence_file"]).read_text())
        tail = (ev["stdout"].strip().splitlines() or [""])[-3:]
        out += [f"### {r['test']} — {'PASS' if r['passed'] else 'FAIL'}", "",
                f"* Command: `{' '.join(ev['command']).replace(str(ROOT) + '/', '')}`",
                f"* Exit code: {ev['exit_code']} (expected {ev['expected_exit_code']}), duration {ev['duration_s']} s",
                f"* Output SHA-256: `{ev['output_sha256']}` · evidence SHA-256: `{r['evidence_sha256']}`",
                "* Output tail:", "", "```", *tail, "```", ""]
    (ROOT / "STAGE_01_VERIFICATION.md").write_text("\n".join(out))
    print(f"STAGE_01_VERIFICATION.md written for run {run} ({gate['status']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
